float qsin_rad(float x) {
    // 规范化到[0, 2π)
    x = fmodf(x, TWO_PI);
    if (x < 0) x += TWO_PI;

    float sign = 1.0f;

    // 象限处理（缩小弧度）
    if (x > THREE_PI / 2.0f) {
        x = TWO_PI - x;
        sign = -1.0f;
    }
    else if (x > (float)M_PI) {
        x = x - (float)M_PI;
        sign = -1.0f;
    }
    else if (x > PI_OVER_TWO) {
        x = (float)M_PI - x;
    }

    // 计算索引（四舍五入）
    float index_f = x *636.0f;
    int idx = (int)(index_f + 0.5f);
    if (idx < 0) idx = 0;
    if (idx >= 1000) idx = 999;

    return sign * sin_val[idx];
}


// 余弦函数（弧度参数）
float qcos_rad(float x) {
    return qsin_rad(x + PI_OVER_TWO);
}

// 正切函数（弧度参数）
float qtan_rad(float x) {

    // 正常的计算流程
    float s = qsin_rad(x);
    float c = qcos_rad(x);

    // 避免除零错误
    if (fabsf(c) < 1e-1f) {
        return tanf(x);
    }

    return s / c;
}

// 反正弦函数
float qasin_rad(float x) {
    // 钳制输入值
    if (x < -1.0f) x = -1.0f;
    if (x > 1.0f) x = 1.0f;

    float sign = 1.0f;
    float abs_x = x;

    // 处理负值
    if (x < 0) {
        sign = -1.0f;
        abs_x = -x;
    }

    // 计算索引（四舍五入）
    float index_f = abs_x * 999.0f;
    int idx = (int)(index_f + 0.5f);
    if (idx < 0) idx = 0;
    if (idx >= 1000) idx = 999;

    return sign * asin_val[idx];
}

// 反余弦函数
float qacos_rad(float x) {
    return (float)PI_OVER_TWO - qasin_rad(x);
}

// 反正切函数
float qatan_rad(float x) {
    float sign = 1.0f;
    float abs_x = x;

    // 处理负值
    if (x < 0) {
        sign = -1.0f;
        abs_x = -x;
    }

    float result;

    if (abs_x <= 1.0f) {
        // 对于 |x| <= 1，直接查表
        float index_f = abs_x * 999.0f;
        int idx = (int)(index_f + 0.5f);
        if (idx < 0) idx = 0;
        if (idx >= 1000) idx = 999;
        result = atan_val[idx];
    }
    else {
        // 对于 |x| > 1，使用恒等式 atan(x) = π/2 - atan(1/x)
        float reciprocal = 1.0f / abs_x;
        float index_f = reciprocal * 999.0f;
        int idx = (int)(index_f + 0.5f);
        if (idx < 0) idx = 0;
        if (idx >= 1000) idx = 999;

        float atan_reciprocal = atan_val[idx];
        result = (float)PI_OVER_TWO - atan_reciprocal;
    }

    return sign * result;
}

// 反正切函数（两个参数版本）
float qatan2_rad(float y, float x) {
    if (x > 0) {
        // 第一、四象限
        return qatan_rad(y / x);
    }
    else if (x < 0) {
        if (y >= 0) {
            // 第二象限
            return qatan_rad(y / x) + (float)M_PI;
        }
        else {
            // 第三象限
            return qatan_rad(y / x) - (float)M_PI;
        }
    }
    else {
        if (y > 0) {
            return (float)PI_OVER_TWO;
        }
        else if (y < 0) {
            return -(float)PI_OVER_TWO;
        }
        else {
            return 0.0f;
        }
    }
}


